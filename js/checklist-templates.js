// какой шаблон подходит запросу
export function pickTemplate(r) {
  const t = `${r.summary || ''} ${r.original_message || ''}`.toLowerCase();
  const has = (re) => re.test(t);
  switch (r.category) {
    case 'Transport':
      if (has(/в аэропорт|вылет|to the airport|départ|departure/)) return 'airport_out';
      if (has(/аэропорт|рейс|прил[её]т|cdg|ory|nce|gva|dxb|lhr|airport|arrival|flight|vol\b/)) return 'airport_in';
      return 'transfer';
    case 'Dining': return 'dining';
    case 'Spa & Wellness': return 'spa';
    case 'Accommodation': return 'hotel';
    case 'Gifts & Events': return has(/цвет|букет|пион|роз|flower|fleur/) ? 'flowers' : 'gift';
    case 'Activities': return 'activity';
    case 'Health & Fitness': return 'health';
    default: return 'other';
  }
}
