import assert from 'node:assert/strict';
import { precheckWindow, partnerMessage, langFor, countdown, H } from '../js/precheck-core.js';
const now = Date.parse('2026-11-25T10:00:00Z');
const at = (h) => new Date(now + h * H).toISOString();
assert.equal(precheckWindow(at(30), now), null, 'дальше 24 ч — тишина');
assert.equal(precheckWindow(at(20), now), 'T24');
assert.equal(precheckWindow(at(20), now, { precheck24h_done: true }), null);
assert.equal(precheckWindow(at(2), now), 'T3');
assert.equal(precheckWindow(at(2), now, { precheck24h_done: true }), 'T3', 'финальный контроль независим от реконфирмации');
assert.equal(precheckWindow(at(2), now, { precheck3h_done: true }), null);
assert.equal(precheckWindow(at(-0.2), now), 'T3', 'событие только началось — ещё показываем');
assert.equal(precheckWindow(at(-2), now), null, 'прошло');
assert.equal(precheckWindow('нет', now), null);
assert.equal(countdown(at(2.5), now), '2:30');
assert.equal(langFor('de'), 'de'); assert.equal(langFor('JP'), 'en'); assert.equal(langFor(null), 'en');
const m = partnerMessage({ lang: 'en', whenIso: at(20), tz: 'Europe/Berlin', venue: 'Spa Alpha', guest: 'Ivan P.', allergies: ['nuts'], pref: 'female therapist', pickup: 'Hotel lobby' });
assert.match(m, /Spa Alpha/); assert.match(m, /Ivan P\./); assert.match(m, /nuts/); assert.match(m, /female therapist/); assert.match(m, /Hotel lobby/);
assert.ok(!/заметк|note/i.test(m), 'личных заметок в тексте нет');
for (const l of ['fr', 'de', 'it', 'es', 'ru']) assert.ok(partnerMessage({ lang: l, whenIso: at(5), venue: 'X', guest: 'G' }).length > 40);
console.log('precheck ok');
